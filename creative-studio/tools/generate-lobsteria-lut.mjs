#!/usr/bin/env node
// Generates creative-studio/luts/lobsteria-warm.cube — a real 3D LUT
// implementing the "warm amber, food brightest" grade from
// camera-course-reference.md: warm highlights, a touch of teal in the
// shadows, slightly lifted blacks, mild contrast, slightly lower
// saturation. Built from scratch (not downloaded) so there's no
// third-party licensing question and it matches the documented Lobsteria
// look exactly rather than a generic "warm" preset.
//
// Run: node creative-studio/tools/generate-lobsteria-lut.mjs

import { writeFileSync, mkdirSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const SIZE = 17; // LUT_3D_SIZE — 17^3 = 4913 entries, standard quality/size tradeoff

// Per-channel lift (shadows) / gain (highlights). Red gets a small POSITIVE
// gain boost and near-zero lift (warm highlights, no red added to shadows).
// Blue/green get a small POSITIVE lift (teal-leaning shadows) and a small
// NEGATIVE gain on blue specifically (less blue in highlights = warm).
const CHANNELS = {
  r: { lift: 0.0, gain: 1.08 },
  g: { lift: 0.012, gain: 1.0 },
  b: { lift: 0.02, gain: 0.92 },
};

const CONTRAST = 1.06; // mild S-curve around midgray
const SATURATION = 0.93; // "slightly lower saturation" per the spec

function applyChannel(inVal, { lift, gain }) {
  let out = lift * (1 - inVal) + inVal * gain;
  out = (out - 0.5) * CONTRAST + 0.5; // contrast
  return out;
}

function clamp01(v) {
  return Math.min(1, Math.max(0, v));
}

function gradeSample(r, g, b) {
  let or_ = applyChannel(r, CHANNELS.r);
  let og = applyChannel(g, CHANNELS.g);
  let ob = applyChannel(b, CHANNELS.b);

  // Desaturate slightly toward luma, computed from the GRADED values.
  const luma = 0.299 * or_ + 0.587 * og + 0.114 * ob;
  or_ = luma + (or_ - luma) * SATURATION;
  og = luma + (og - luma) * SATURATION;
  ob = luma + (ob - luma) * SATURATION;

  return [clamp01(or_), clamp01(og), clamp01(ob)];
}

function buildCube() {
  const lines = [
    'TITLE "Lobsteria Warm"',
    `LUT_3D_SIZE ${SIZE}`,
    '# Generated by creative-studio/tools/generate-lobsteria-lut.mjs',
    '# Warm highlights, teal-leaning shadows, mild contrast, -7% saturation',
    '# Implements the "warm amber, food brightest" grade from camera-course-reference.md',
  ];

  // .cube format iterates blue slowest... actually standard order is R
  // fastest, then G, then B slowest (confirmed against the Adobe/Resolve
  // .cube spec: "red is the fastest-changing index").
  for (let bi = 0; bi < SIZE; bi++) {
    const b = bi / (SIZE - 1);
    for (let gi = 0; gi < SIZE; gi++) {
      const g = gi / (SIZE - 1);
      for (let ri = 0; ri < SIZE; ri++) {
        const r = ri / (SIZE - 1);
        const [or_, og, ob] = gradeSample(r, g, b);
        lines.push(`${or_.toFixed(6)} ${og.toFixed(6)} ${ob.toFixed(6)}`);
      }
    }
  }
  return lines.join('\n') + '\n';
}

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.resolve(__dirname, '../luts');
const outPath = path.join(outDir, 'lobsteria-warm.cube');

mkdirSync(outDir, { recursive: true });
writeFileSync(outPath, buildCube());
console.log(`Wrote ${outPath}`);
